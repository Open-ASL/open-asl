import type { HexId } from '@asl/engine';

/*
 * Building heights per board (ASLRB B23.2–B23.23), judged from the board art, not from VASL's terrain codes.
 *
 * - single: a single-hex building without a stairwell symbol, a Single Story House (B23.21): ground level only.
 * - two: a multi-hex building without a stairwell symbol, a Two Story House (B23.22): level 1 in every hex, each
 *   with an inherent stairwell; a 1½-level obstacle.
 * - multi: a building with a printed stairwell symbol (the small white square in place of the hex centre dot), a
 *   Multi-Story Building (B23.23): levels 1 and 2, stairs only in its stairwell hexes; a 2½-level obstacle.
 *
 * How it was judged (2026-11-07): every building hex centre of the high-resolution board art
 * (apps/web/art/boards) was cropped and checked for a stairwell square (none on boards t–z: every
 * centre mark is a round dot), and every pair of adjacent building hexes was cropped round their common hexside to
 * see whether the depiction crosses it (one building) or not. The hexes of each building are the importer's
 * buildingId grouping, which agreed with the art at every one of the 262 hexsides looked at.
 *
 * `vasl` is the VASL LOSData terrain code of the building's pixels (40/50 stone/wooden, 41/51 "1 Level", 203/206
 * "Multiple"), kept as a hint only. It agrees with the art on every building of boards t–z: 41/51 exactly on the
 * multi-hex buildings, 40/50/203/206 on the single-hex ones. A `note` explains anything unusual.
 *
 * Only the full ASL ruleset reads levels (`asl/locations.ts` via `'hex.locations'`); the Starter Kit plays every
 * building at ground level.
 */

export type BuildingKind = 'single' | 'two' | 'multi';

export interface BuildingLevels {
  kind: BuildingKind;
  hexes: HexId[];
  /** Multi-Story Buildings only: the hexes with a printed stairwell. */
  stairwells?: HexId[];
  vasl: number;
  note?: string;
}

